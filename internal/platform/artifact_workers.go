type ReleaseProfileRegistration struct {
	ID     string `json:"id"`
	Kind   string `json:"kind"`
	SHA256 string `json:"sha256"`
}
type ReleaseWorker struct {
	ID         string                       `json:"id"`
	ProjectID  string                       `json:"project_id"`
	WorkerID   string                       `json:"worker_id"`
	Version    int                          `json:"version"`
	Status     string                       `json:"status"`
	Profiles   []ReleaseProfileRegistration `json:"profiles"`
	Deployment bool                         `json:"deployment"`
	CreatedAt  string                       `json:"created_at"`
	ExpiresAt  string                       `json:"expires_at"`
}

// Human release administration requires the actual browser credential and current
// domain admin role in this same transaction, before any receipt is recovered.
func (s *Service) artifactAdminTx(ctx context.Context, tx *sql.Tx, actor Actor, project string) (*authorizedCommand, error) {
	return s.artifactAdminSubjectTx(ctx, tx, actor, project, "")
}
func (s *Service) artifactAdminSubjectTx(ctx context.Context, tx *sql.Tx, actor Actor, project, subject string) (*authorizedCommand, error) {
	auth, err := s.authorizeTx(ctx, tx, actor, commandTarget{tenantID: actor.credential.tenantID, projectID: project, subjectID: subject}, purposeBrowserProjectWrite)
	if err != nil {
		return nil, err
	}
	p := auth.currentPrincipal
	if !orgAdmin(p) {
		var role string
		if err = tx.QueryRowContext(ctx, s.q(s.currentSQL(`SELECT role FROM suma_project_members WHERE project_id=? AND user_id=?`)), project, p.ID).Scan(&role); err != nil || role != "admin" {
			return nil, forbidden()
		}
	}
	return auth, nil
}

func (s *Service) RegisterReleaseWorker(ctx context.Context, actor Actor, project string, m map[string]any) (map[string]any, error) {
	p := actor.Projection()

	var request struct {
		ProjectID      string                       `json:"project_id"`
		WorkerID       string                       `json:"worker_id"`
		Profiles       []ReleaseProfileRegistration `json:"profiles"`
		Deployment     bool                         `json:"deployment"`
		IdempotencyKey string                       `json:"idempotency_key"`
	}
	if err := releaseDecode(m, &request); err != nil {
		return nil, err
	}
	worker := str(m, "worker_id")
	// Shared machine identities are generated by their owning pool. Reserving
	// this namespace prevents a project registration from shadowing that same
	// worker in tool inventory/profile lookups, including case-folded databases.
	if strings.HasPrefix(strings.ToLower(worker), "pool-") {
		return nil, &APIError{400, "reserved_worker_id", "pool- 前缀保留给资源池生成的执行身份，请选择其他项目节点标识", nil}
	}
	if !releasecontract.ValidProfileID(worker) {
		return nil, invalid("执行节点标识应为 1–100 位字母、数字、点、短横线或下划线")
	}
	var profiles []ReleaseProfileRegistration
	b, err := json.Marshal(m["profiles"])
	if err != nil || json.Unmarshal(b, &profiles) != nil || len(profiles) > 32 {
		return nil, invalid("发布命令配置无效")
	}
	seen := map[string]bool{}
	for _, pr := range profiles {
		if !releasecontract.ValidProfileID(pr.ID) || !releasecontract.ValidDigest(pr.SHA256) || pr.Kind != "build" && pr.Kind != "package_test" || seen[pr.ID] {
			return nil, invalid("命令需唯一标识、种类及真实配置摘要")
		}
		seen[pr.ID] = true
	}
	deployment, _ := m["deployment"].(bool)
	// A stable execution identity may be registered without release capabilities.
	// Tool inventories reuse this identity, while release authorization below
	// still requires its exact build/package/deployment grant.
	ctx, tx, cancel, err := s.beginAuthorityTx(ctx)
	if err != nil {
		return nil, err
	}
	defer cancel()
	defer tx.Rollback()
	auth, err := s.artifactAdminTx(ctx, tx, actor, project)
	if err != nil {
		return nil, err
	}
	p = auth.currentPrincipal
	hash, replay, err := s.commandReceipt(ctx, auth, str(m, "idempotency_key"), map[string]any{"register_release_worker": m})
	if err != nil {
		return nil, err
	}
	if replay {
		var out map[string]any
		err = json.Unmarshal([]byte(hash), &out)
		return out, err
	}
	var count int
	if err = tx.QueryRowContext(ctx, s.q(`SELECT COUNT(*) FROM suma_release_workers WHERE tenant_id=? AND project_id=? AND worker_id=?`), p.TenantID, project, worker).Scan(&count); err != nil {
		return nil, err
	}
	if count != 0 {
		return nil, conflict("执行节点标识已有登记；请使用不同标识，不能覆盖历史凭证")
	}
	id := newID()
	issued, err := s.issueRegisteredRunnerTx(ctx, tx, auth, "release-worker:"+worker, str(m, "idempotency_key"))
	if err != nil {
		return nil, err
	}
	secret, expires := issued.Token, issued.ExpiresAt
	at := auth.checkedAt.Format(time.RFC3339Nano)
	if _, err = tx.ExecContext(ctx, s.q(`INSERT INTO suma_release_workers(id,tenant_id,project_id,worker_id,token_hash,version,status,profiles,deployment,created_by,created_at,expires_at)VALUES(?,?,?,?,?,1,'active',?,?,?,?,?)`), id, p.TenantID, project, worker, digest(secret), stringify(profiles), deployment, p.ID, at, expires); err != nil {
		return nil, err
	}
	out := map[string]any{"id": id, "project_id": project, "worker_id": worker, "version": 1, "status": "active", "profiles": profiles, "deployment": deployment, "created_at": at, "expires_at": expires}
	if err = s.saveCommandReceipt(ctx, auth, str(m, "idempotency_key"), hash, out); err != nil {
		return nil, err
	}
	if err = s.commandActivity(ctx, auth, "release_worker.registered", id, worker); err != nil {
		return nil, err
	}
	if err = tx.Commit(); err != nil {
		return nil, err
	}
	out["token"] = secret // Once only; neither receipt nor public registry contains the secret.
	return out, nil
}

func (s *Service) RevokeReleaseWorker(ctx context.Context, actor Actor, project, id string, m map[string]any) (ReleaseWorker, error) {
	p := actor.Projection()

	var out ReleaseWorker
	var req struct {
		ProjectID       string `json:"project_id"`
		ExpectedVersion int    `json:"expected_version"`
		IdempotencyKey  string `json:"idempotency_key"`
		Status          string `json:"status"`
	}
	if err := releaseDecode(m, &req); err != nil {
		return out, err
	}
	if req.Status != "revoked" || req.ExpectedVersion < 1 {
		return out, invalid("发布凭证仅能以明确版本撤销")
	}
	ctx, tx, cancel, err := s.beginAuthorityTx(ctx)
	if err != nil {
		return out, err
	}
	defer cancel()
	defer tx.Rollback()
	// Discover target subject before the complete organization/account lock union.
	var targetSubject, discoveredDigest string
	if err = tx.QueryRowContext(ctx, s.q(`SELECT x.user_id,w.token_hash FROM suma_release_workers w JOIN suma_sessions x ON x.token_hash=w.token_hash WHERE w.tenant_id=? AND w.project_id=? AND w.id=?`), p.TenantID, project, id).Scan(&targetSubject, &discoveredDigest); err != nil {
		return out, missing()
	}
	auth, err := s.artifactAdminSubjectTx(ctx, tx, actor, project, targetSubject)
	if err != nil {
		return out, err
	}
	p = auth.currentPrincipal
	hash, replay, err := s.commandReceipt(ctx, auth, req.IdempotencyKey, map[string]any{"revoke_release_worker": id, "body": m})
	if err != nil {
		return out, err
	}
	if replay {
		err = json.Unmarshal([]byte(hash), &out)
		return out, err
	}
	var raw, tokenHash string
	if err = tx.QueryRowContext(ctx, s.q(s.currentSQL(`SELECT id,project_id,worker_id,version,status,profiles,deployment,created_at,expires_at,token_hash FROM suma_release_workers WHERE tenant_id=? AND project_id=? AND id=?`)), p.TenantID, project, id).Scan(&out.ID, &out.ProjectID, &out.WorkerID, &out.Version, &out.Status, &raw, &out.Deployment, &out.CreatedAt, &out.ExpiresAt, &tokenHash); err != nil {
		return out, missing()
	}
	if tokenHash != discoveredDigest {
		return out, conflict("发布执行凭证已变化，请重试")
	}
	if err = json.Unmarshal([]byte(raw), &out.Profiles); err != nil {
		return out, err
	}
	if out.Version != req.ExpectedVersion || out.Status != "active" {
		return out, conflict("发布执行凭证已变化，请刷新")
	}
	if _, err = tx.ExecContext(ctx, s.q(`UPDATE suma_credential_authority SET revoked=1 WHERE token_hash=?`), tokenHash); err != nil {
		return out, err
	}
	if _, err = tx.ExecContext(ctx, s.q(`UPDATE suma_credential_slots SET revoked=1 WHERE id IN (SELECT slot_id FROM suma_credential_authority WHERE token_hash=?)`), tokenHash); err != nil {
		return out, err
	}
	if _, err = tx.ExecContext(ctx, s.q(`UPDATE suma_release_workers SET status='revoked',version=version+1 WHERE id=? AND version=?`), id, out.Version); err != nil {
		return out, err
	}
	out.Status = "revoked"
	out.Version++
	if err = s.commandActivity(ctx, auth, "release_worker.revoked", id, out.WorkerID); err != nil {
		return out, err
	}
	if err = s.saveCommandReceipt(ctx, auth, req.IdempotencyKey, hash, out); err != nil {
		return out, err
	}
	return out, tx.Commit()
}

func (s *Service) releaseWorkerTx(ctx context.Context, tx *sql.Tx, actor Actor, project, worker, profile, profileHash, kind string) (*authorizedCommand, error) {
	auth, err := s.authorizeTx(ctx, tx, actor, commandTarget{tenantID: actor.credential.tenantID, projectID: project}, purposeRunnerWrite)
	if err != nil {
		return nil, err
	}
	if err = s.releaseWorkerBindingTx(ctx, tx, auth, worker, profile, profileHash, kind); err != nil {
		return nil, err
	}
	return auth, nil
}

// Binding validation consumes an existing same-transaction Runner proof. It
// deliberately takes no organization/account lock after scheduler selection.
func (s *Service) releaseWorkerBindingTx(ctx context.Context, tx *sql.Tx, auth *authorizedCommand, worker, profile, profileHash, kind string) error {
	if auth == nil {
		return unauthenticated()
	}
	if err := auth.assertTx(tx, auth.target, auth.purpose); err != nil {
		return err
	}
	if auth.actor.kind != actorProjectRunner || auth.target.projectID == "" || auth.purpose != purposeRunnerRead && auth.purpose != purposeRunnerWrite {
		return forbidden()
	}
	project := auth.target.projectID
	p := auth.currentPrincipal
	var actual, state, raw string
	var deploy bool
	if err := tx.QueryRowContext(ctx, s.q(s.currentSQL(`SELECT w.worker_id,w.status,w.profiles,w.deployment FROM suma_release_workers w JOIN suma_sessions x ON x.token_hash=w.token_hash JOIN suma_token_scopes t ON t.token_hash=x.token_hash WHERE w.token_hash=? AND w.tenant_id=? AND w.project_id=? AND x.user_id=? AND x.tenant_id=w.tenant_id AND t.kind='runner' AND t.project_id=w.project_id`)), auth.actor.credential.digest, p.TenantID, project, p.ID).Scan(&actual, &state, &raw, &deploy); err != nil || state != "active" || subtle.ConstantTimeCompare([]byte(actual), []byte(worker)) != 1 {
		return forbidden()
	}
	if kind == "deployment" {
		if !deploy {
			return forbidden()
		}
		return nil
	}
	if kind == "identity" {
		return nil
	}
	var profiles []ReleaseProfileRegistration
	if json.Unmarshal([]byte(raw), &profiles) != nil {
		return forbidden()
	}
	for _, v := range profiles {
		if v.ID == profile && v.Kind == kind && v.SHA256 == profileHash {
			return nil
		}
	}
	return forbidden()
}

// The independent runner's current Grant/slot/source is checked even while its
// old suma_sessions/scope rows remain available for audit after revocation.
func (s *Service) runnerIdentityTx(ctx context.Context, tx *sql.Tx, actor Actor, project, worker string) (*authorizedCommand, error) {
	auth, err := s.authorizeTx(ctx, tx, actor, commandTarget{tenantID: actor.credential.tenantID, projectID: project}, purposeRunnerWrite)
	if err != nil {
		return nil, err
	}
	if err = s.runnerIdentityBindingTx(ctx, tx, auth, worker); err != nil {
		return nil, err
	}
	return auth, nil
}
func (s *Service) runnerIdentityBindingTx(ctx context.Context, tx *sql.Tx, auth *authorizedCommand, worker string) error {
	if auth == nil {
		return unauthenticated()
	}
	if err := auth.assertTx(tx, auth.target, auth.purpose); err != nil {
		return err
	}
	if auth.actor.kind != actorProjectRunner || auth.purpose != purposeRunnerRead && auth.purpose != purposeRunnerWrite {
		return forbidden()
	}
	project := auth.target.projectID
	p := auth.currentPrincipal
	var bound string
	err := tx.QueryRowContext(ctx, s.q(s.currentSQL(`SELECT worker_id FROM suma_release_workers WHERE token_hash=?`)), auth.actor.credential.digest).Scan(&bound)
	if err != nil && err != sql.ErrNoRows {
		return err
	}
	if bound != "" && bound != worker {
		return forbidden()
	}
	var expected string
	err = tx.QueryRowContext(ctx, s.q(s.currentSQL(`SELECT token_hash FROM suma_release_workers WHERE tenant_id=? AND project_id=? AND worker_id=?`)), p.TenantID, project, worker).Scan(&expected)
	if err != nil && err != sql.ErrNoRows {
		return err
	}
	if expected != "" {
		if expected != auth.actor.credential.digest {
			return forbidden()
		}
		if err = s.releaseWorkerBindingTx(ctx, tx, auth, worker, "", "", "identity"); err != nil {
			return err
		}
		return nil
	}
	return nil
}

func (s *Service) releaseClaimEligibleTx(ctx context.Context, tx *sql.Tx, auth *authorizedCommand, worker, run string) (bool, error) {
	if auth == nil {
		return false, unauthenticated()
	}
	if err := auth.assertTx(tx, auth.target, auth.purpose); err != nil {
		return false, err
	}
	p, project := auth.currentPrincipal, auth.target.projectID

	var n int
	if err := tx.QueryRowContext(ctx, s.q(`SELECT COUNT(*) FROM dag_managed_workflows WHERE tenant_id=? AND project_id=? AND run_id=?`), p.TenantID, project, run).Scan(&n); err != nil {
		return false, err
	}
	if n == 0 {
		return true, nil
	}
	if task, err := s.TaskDispatchRunTx(ctx, tx, p.TenantID, project, run); err != nil {
		return false, err
	} else if task {
		return true, nil
	}
	if integration, err := s.RepositoryIntegrationRunTx(ctx, tx, p.TenantID, project, run); err != nil {
		return false, err
	} else if integration {
		return true, nil
	}
	// Planning is a read-only managed workflow, not a deployment. Its creator,
	// source and exact tool are checked by planning and tool admission below.
	if _, planning, err := s.planningExecutionRecordTx(ctx, tx, p.TenantID, project, run); err != nil {
		return false, err
	} else if planning {
		return true, nil
	}
	if _, extraction, err := s.knowledgeIntelligenceExecutionRecordTx(ctx, tx, p.TenantID, project, run); err != nil {
		return false, err
	} else if extraction {
		return true, nil
	}
	if err := tx.QueryRowContext(ctx, s.q(`SELECT COUNT(*) FROM suma_release_workers WHERE tenant_id=? AND project_id=? AND worker_id=? AND token_hash=? AND deployment=1 AND status='active'`), p.TenantID, project, worker, auth.actor.credential.digest).Scan(&n); err != nil {
		return false, err
	}
	return n == 1, nil
}

func (s *Service) ReleaseWorkers(ctx context.Context, actor Actor, project string) ([]ReleaseWorker, error) {
	var result0 []ReleaseWorker
	err := s.withCurrentCRead(ctx, actor, commandTarget{tenantID: actor.credential.tenantID, projectID: project}, purposeProjectRead, func(ctx context.Context, auth *authorizedCommand) error {
		bounded, cancel := context.WithDeadline(ctx, auth.deadline)
		defer cancel()
		var e error
		result0, e = s.readReleaseWorkersTx(bounded, auth, project)
		return e
	})
	return result0, err
}
func (s *Service) readReleaseWorkersTx(ctx context.Context, auth *authorizedCommand, project string) ([]ReleaseWorker, error) {
	if auth == nil {
		return nil, unauthenticated()
	}
	if e := auth.assertTx(auth.tx, auth.target, auth.purpose); e != nil {
		return nil, e
	}
	if auth.target.projectID != project {
		return nil, forbidden()
	}

	tx, p := auth.tx, auth.currentPrincipal
	var err error

	rows, err := tx.QueryContext(ctx, s.q(`SELECT id,project_id,worker_id,version,status,profiles,deployment,created_at,expires_at FROM suma_release_workers WHERE tenant_id=? AND project_id=? ORDER BY created_at DESC,id`), p.TenantID, project)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []ReleaseWorker{}
	for rows.Next() {
		var w ReleaseWorker
		var raw string
		if err = rows.Scan(&w.ID, &w.ProjectID, &w.WorkerID, &w.Version, &w.Status, &raw, &w.Deployment, &w.CreatedAt, &w.ExpiresAt); err != nil {
			return nil, err
		}
		if err = json.Unmarshal([]byte(raw), &w.Profiles); err != nil {
			return nil, err
		}
		out = append(out, w)
	}
	return out, rows.Err()

}
