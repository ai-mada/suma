const Protocol = "claude-sdk-v1"
const SDKVersion = "0.3.314"
const CLIVersion = "2.1.314"
const InputProtocol = "claude-sdk-input-v1"
const MaxPayloadBytes = 64 << 10
const MaxCallbacks = 32

// Basis correlates one actual SDK callback. CallbackID is generated by the
// Suma host; ToolUseID and SessionID come from the pinned SDK, not from users.
type Basis struct {
	SessionID           string `json:"session_id"`
	ToolUseID           string `json:"tool_use_id"`
	RequestID           string `json:"request_id"`
	CallbackID          string `json:"callback_id"`
	ConfigurationSHA256 string `json:"configuration_sha256"`
	ParamsSHA256        string `json:"params_sha256"`
}
type ClaudePermissionSource struct {
	Basis
	ToolName  string `json:"tool_name"`
	InputJSON string `json:"input_json"`
}
type ClaudePermissionChoice struct {
	Outcome string `json:"outcome"`
	Reason  string `json:"reason,omitempty"`
}
type ClaudeQuestionOption struct {
	ID          string `json:"id"`
	Label       string `json:"label"`
	Description string `json:"description"`
}
type ClaudeQuestion struct {
	ID            string                 `json:"id"`
	Prompt        string                 `json:"prompt"`
	Header        string                 `json:"header"`
	Options       []ClaudeQuestionOption `json:"options"`
	AllowMultiple bool                   `json:"allow_multiple"`
}
type ClaudeInputRequest struct {
	Basis
	InputJSON string           `json:"input_json"`
	Questions []ClaudeQuestion `json:"questions"`
}
type ClaudeInputSelection struct {
	QuestionID string   `json:"question_id"`
	OptionIDs  []string `json:"option_ids"`
}
type ClaudeInputDecision struct {
	Outcome string                 `json:"outcome"`
	Answers []ClaudeInputSelection `json:"answers,omitempty"`
	Reason  string                 `json:"reason,omitempty"`
}
type ClaudePermissionEvidence struct {
	PermissionID string `json:"permission_id"`
	Basis
	ToolName    string                `json:"tool_name"`
	Observation *delivery.Observation `json:"observation,omitempty"`
}
type ClaudeInputEvidence struct {
	InputID string `json:"input_id"`
	Basis
	QuestionCount int                   `json:"question_count"`
	Observation   *delivery.Observation `json:"observation,omitempty"`
}
type PermissionSource = ClaudePermissionSource
type PermissionChoice = ClaudePermissionChoice
type PermissionObservation = delivery.Observation
type InputRequest = ClaudeInputRequest
type InputDecision = ClaudeInputDecision
type InputSelection = ClaudeInputSelection
type Question = ClaudeQuestion
type Option = ClaudeQuestionOption
type PermissionEvidence = ClaudePermissionEvidence
type InputEvidence = ClaudeInputEvidence

func text(v string, maximum int, required bool) bool {
	if !required && v == "" {
		return true
	}
	return v != "" && len(v) <= maximum && utf8.ValidString(v) && strings.TrimSpace(v) == v && strings.IndexFunc(v, func(r rune) bool { return unicode.IsControl(r) && r != '\n' && r != '\t' }) < 0
}
func ID(v string) bool { return text(v, 150, true) && strings.IndexFunc(v, unicode.IsSpace) < 0 }
func Digest(v string) bool {
	b, e := hex.DecodeString(v)
	return e == nil && len(b) == 32 && v == strings.ToLower(v)
}
func PayloadDigest(v string) string {
	sum := sha256.Sum256([]byte(v))
	return hex.EncodeToString(sum[:])
}
func ValidateBasis(v Basis) error {
	if !ID(v.SessionID) || !ID(v.ToolUseID) || !ID(v.RequestID) || !ID(v.CallbackID) || !Digest(v.ConfigurationSHA256) || !Digest(v.ParamsSHA256) {
		return fmt.Errorf("invalid Claude SDK callback identity")
	}
	return nil
}
func validPayload(b Basis, raw string) bool {
	var object map[string]any
	return ValidateBasis(b) == nil && len(raw) <= MaxPayloadBytes && PayloadDigest(raw) == b.ParamsSHA256 && strictjson.Decode([]byte(raw), &object, MaxPayloadBytes) == nil && object != nil
}
func permissionTool(name string) bool {
	switch name {
	case "Read", "Edit", "Write", "Glob", "Grep", "Bash":
		return true
	}
	return false
}
func ValidatePermissionSource(v PermissionSource) error {
	if !permissionTool(v.ToolName) || !validPayload(v.Basis, v.InputJSON) {
		return fmt.Errorf("invalid Claude SDK permission source")
	}
	return nil
}
func ValidatePermissionChoice(v PermissionChoice) error {
	if (v.Outcome != "allow_once" && v.Outcome != "reject_once") || !text(v.Reason, 2000, false) {
		return fmt.Errorf("invalid Claude SDK one-call decision")
	}
	return nil
}
func PermissionChoiceMatchesSource(source PermissionSource, choice PermissionChoice) bool {
	return ValidatePermissionSource(source) == nil && ValidatePermissionChoice(choice) == nil
}

// Digests use UTF-8 length-prefixed parts, avoiding language-specific JSON
// escaping. They bind the native source and the exact human decision.
func decisionDigest(b Basis, kind string, parts ...string) string {
	values := append([]string{Protocol, kind, b.SessionID, b.ToolUseID, b.RequestID, b.CallbackID, b.ConfigurationSHA256, b.ParamsSHA256}, parts...)
	h := sha256.New()
	for _, v := range values {
		fmt.Fprintf(h, "%d:", len([]byte(v)))
		h.Write([]byte(v))
	}
	return hex.EncodeToString(h.Sum(nil))
}
func PermissionDecisionDigest(source PermissionSource, choice PermissionChoice) (string, error) {
	if !PermissionChoiceMatchesSource(source, choice) {
		return "", fmt.Errorf("invalid Claude SDK permission decision")
	}
	return decisionDigest(source.Basis, "permission", source.ToolName, choice.Outcome, choice.Reason), nil
}

type nativeQuestion struct {
	Question string `json:"question"`
	Header   string `json:"header"`
	Options  []struct {
		Label       string `json:"label"`
		Description string `json:"description"`
	} `json:"options"`
	MultiSelect bool `json:"multiSelect"`
}

func questions(raw string) ([]Question, error) {
	var native struct {
		Questions []nativeQuestion  `json:"questions"`
		Answers   map[string]string `json:"answers,omitempty"`
	}
	if strictjson.Decode([]byte(raw), &native, MaxPayloadBytes) != nil || len(native.Answers) != 0 || len(native.Questions) < 1 || len(native.Questions) > 4 {
		return nil, fmt.Errorf("invalid pinned AskUserQuestion payload")
	}
	out := make([]Question, 0, len(native.Questions))
	prompts := map[string]bool{}
	for i, q := range native.Questions {
		if !text(q.Question, 4000, true) || !text(q.Header, 128, true) || len(q.Options) < 2 || len(q.Options) > 4 || prompts[q.Question] {
			return nil, fmt.Errorf("invalid Claude SDK question")
		}
		prompts[q.Question] = true
		item := Question{ID: "q" + strconv.Itoa(i+1), Prompt: q.Question, Header: q.Header, AllowMultiple: q.MultiSelect, Options: make([]Option, 0, len(q.Options))}
		labels := map[string]bool{}
		for j, o := range q.Options {
			if !text(o.Label, 500, true) || !text(o.Description, 4000, false) || labels[o.Label] {
				return nil, fmt.Errorf("invalid Claude SDK option")
			}
			labels[o.Label] = true
			item.Options = append(item.Options, Option{ID: "o" + strconv.Itoa(j+1), Label: o.Label, Description: o.Description})
		}
		out = append(out, item)
	}
	return out, nil
}
func NewInputRequest(b Basis, raw string) (InputRequest, error) {
	q, err := questions(raw)
	if err != nil || !validPayload(b, raw) {
		return InputRequest{}, fmt.Errorf("invalid Claude SDK question source")
	}
	return InputRequest{Basis: b, InputJSON: raw, Questions: q}, nil
}
func ValidateInputRequest(v InputRequest) error {
	q, err := questions(v.InputJSON)
	if err != nil || !validPayload(v.Basis, v.InputJSON) || !reflect.DeepEqual(q, v.Questions) {
		return fmt.Errorf("Claude SDK question differs from its exact native payload")
	}
	return nil
}
func ValidateInputDecision(source InputRequest, value InputDecision) error {
	if ValidateInputRequest(source) != nil || !text(value.Reason, 2000, false) {
		return fmt.Errorf("invalid Claude SDK input decision")
	}
	if value.Outcome == "cancelled" && len(value.Answers) == 0 {
		return nil
	}
	if value.Outcome != "answered" || len(value.Answers) != len(source.Questions) {
		return fmt.Errorf("incomplete Claude SDK answer")
	}
	seen := map[string]bool{}
	for _, answer := range value.Answers {
		var question *Question
		for i := range source.Questions {
			if source.Questions[i].ID == answer.QuestionID {
				question = &source.Questions[i]
				break
			}
		}
		if question == nil || seen[answer.QuestionID] || len(answer.OptionIDs) < 1 || !question.AllowMultiple && len(answer.OptionIDs) != 1 {
			return fmt.Errorf("invalid Claude SDK question selection")
		}
		seen[answer.QuestionID] = true
		options := map[string]bool{}
		for _, id := range answer.OptionIDs {
			found := false
			for _, o := range question.Options {
				if id == o.ID {
					found = true
					break
				}
			}
			if !found || options[id] {
				return fmt.Errorf("invalid Claude SDK option selection")
			}
			options[id] = true
		}
	}
	return nil
}
func InputDecisionDigest(source InputRequest, value InputDecision) (string, error) {
	if ValidateInputDecision(source, value) != nil {
		return "", fmt.Errorf("invalid Claude SDK input decision")
	}
	parts := []string{value.Outcome, value.Reason}
	answers := append([]InputSelection(nil), value.Answers...)
	sort.Slice(answers, func(i, j int) bool { return answers[i].QuestionID < answers[j].QuestionID })
	for _, a := range answers {
		parts = append(parts, a.QuestionID)
		ids := append([]string(nil), a.OptionIDs...)
		sort.Strings(ids)
		parts = append(parts, ids...)
	}
	return decisionDigest(source.Basis, "input", parts...), nil
}

// NativeAnswers reconstructs the SDK answer by original question and option
// text. Stable platform IDs never escape as fabricated native option IDs.
func NativeAnswers(source InputRequest, value InputDecision) (map[string]string, error) {
	if ValidateInputDecision(source, value) != nil || value.Outcome != "answered" {
		return nil, fmt.Errorf("Claude SDK answer required")
	}
	out := map[string]string{}
	for _, q := range source.Questions {
		for _, a := range value.Answers {
			if q.ID != a.QuestionID {
				continue
			}
			selected := map[string]bool{}
			for _, id := range a.OptionIDs {
				selected[id] = true
			}
			labels := []string{}
			for _, o := range q.Options {
				if selected[o.ID] {
					labels = append(labels, o.Label)
				}
			}
			out[q.Prompt] = strings.Join(labels, ", ")
		}
	}
	return out, nil
}
func ValidatePermissionObservation(v PermissionObservation) error {
	if delivery.Validate(v) != nil || v.RequestResolved {
		return fmt.Errorf("Claude SDK delivery has no native acceptance ACK")
	}
	return nil
}
func ValidateInputObservation(v delivery.Observation) error { return ValidatePermissionObservation(v) }

// RawPayload validates a host JSON value without admitting duplicate fields,
// invalid Unicode or unbounded payloads. It is not an authorization decision.
func RawPayload(raw string) (map[string]any, error) {
	var value map[string]any
	err := strictjson.Decode([]byte(raw), &value, MaxPayloadBytes)
	if err != nil || value == nil {
		return nil, fmt.Errorf("invalid Claude SDK payload")
	}
	return value, nil
}
