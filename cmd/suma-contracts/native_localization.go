package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"

	"github.com/ai-mada/suma/internal/localization"
)

// nativeLocalizationSource projects the Go-owned native diagnostics into a
// standalone typed SDK module. No timestamp, runtime JSON import or second
// hand-maintained translation source participates in the generated artifact.
func nativeLocalizationSource() ([]byte, error) {
	return nativeLocalizationSourceFrom(localization.NativeCatalog())
}

func nativeLocalizationSourceFrom(definitions []localization.Definition) ([]byte, error) {
	type entry struct {
		En     string            `json:"en"`
		Zh     string            `json:"zh"`
		Params map[string]string `json:"params,omitempty"`
	}
	catalog := make(map[string]entry, len(definitions))
	for _, d := range definitions {
		if !localization.IsNativeMessageKey(d.Key) || d.SourceTemplate == "" || d.SourceTemplate != d.Texts[localization.EnUS] || d.Texts[localization.ZhCN] == "" {
			return nil, fmt.Errorf("invalid native localization definition: %s", d.Key)
		}
		if _, exists := catalog[d.Key]; exists {
			return nil, fmt.Errorf("duplicate native localization definition: %s", d.Key)
		}
		params := map[string]string{}
		for _, parameter := range d.Parameters {
			if parameter.Kind != localization.Integer && parameter.Kind != localization.Text {
				return nil, fmt.Errorf("unsupported native localization parameter kind: %s", d.Key)
			}
			if _, exists := params[parameter.Name]; exists {
				return nil, fmt.Errorf("duplicate native localization parameter: %s", d.Key)
			}
			params[parameter.Name] = string(parameter.Kind)
		}
		catalog[d.Key] = entry{En: d.Texts[localization.EnUS], Zh: d.Texts[localization.ZhCN], Params: params}
	}
	if len(catalog) != len(localization.NativeCatalog()) {
		return nil, fmt.Errorf("incomplete native localization catalog")
	}
	// encoding/json sorts map keys. Sorting explicitly documents that the SDK
	// union and serialized entries are independent of source declaration order.
	keys := make([]string, 0, len(catalog))
	for key := range catalog {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var output bytes.Buffer
	output.WriteString("// Generated by go run ./cmd/suma-contracts. Do not edit.\n")
	output.WriteString("// Source: internal/localization/catalog_native.go; named-dot-v1 templates.\n")
	output.WriteString("// Display metadata only; original diagnostics, model/tool payloads and evidence remain unchanged.\n")
	output.WriteString("export type NativeCatalogEntry={en:string;zh:string;params?:Record<string,'integer'|'text'>};\n")
	output.WriteString("export const nativeCatalog={\n")
	for _, key := range keys {
		var encoded bytes.Buffer
		encoder := json.NewEncoder(&encoded)
		encoder.SetEscapeHTML(false)
		if err := encoder.Encode(catalog[key]); err != nil {
			return nil, err
		}
		quotedKey, err := json.Marshal(key)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&output, " %s:%s,\n", quotedKey, bytes.TrimSuffix(encoded.Bytes(), []byte{'\n'}))
	}
	output.WriteString("} as const satisfies Record<string,NativeCatalogEntry>;\n")
	output.WriteString("export type NativeMessageKey=keyof typeof nativeCatalog;\n")
	return output.Bytes(), nil
}
