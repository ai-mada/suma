func knowledgeProjectionWireType(t reflect.Type, f reflect.StructField, original string) string {
	name := wireModelName(t)
	if strings.HasPrefix(name, "KnowledgeIndex") && f.Name == "Protocol" {
		return `"suma-knowledge-index-v1"`
	}
	if name == "KnowledgeIndexSource" && f.Name == "Kind" || name == "KnowledgeIndexSearchRequest" && f.Name == "SourceKind" {
		return `"documents" | "project_knowledge"`
	}
	if name == "KnowledgeIndexLocator" && f.Name == "Unit" {
		return `"unicode_codepoints"`
	}
	if (name == "KnowledgeIndexRequest" || name == "KnowledgeIndexReceipt" || name == "ProjectKnowledgeProjectionEvent") && f.Name == "Action" {
		return `"upsert" | "delete"`
	}
	if name == "KnowledgeIndexReceipt" && f.Name == "Disposition" {
		return `"applied" | "duplicate" | "obsolete"`
	}
	if (name == "KnowledgeIndexSearchResult" || name == "ProjectKnowledgeIndexSearch") && f.Name == "Mode" {
		return `"lancedb_fts" | "lancedb_hybrid" | "oceanbase_fts" | "oceanbase_hybrid"`
	}
	if (name == "ProjectKnowledgeIndexQuery" || name == "ProjectKnowledgeIndexHit") && f.Name == "Kind" {
		return `"memory" | "spec" | "skill"`
	}
	if name == "ProjectKnowledgeProjectionEvent" && f.Name == "State" {
		return `"pending" | "indexed" | "failed"`
	}
	if name == "ProjectKnowledgeIndexSearch" && f.Name == "Scope" {
		return `"provider_candidates"`
	}
	if name == "ProjectKnowledgeIndexStatus" {
		switch f.Name {
		case "Domain":
			return `"project_knowledge"`
		case "Coverage":
			return `"outbox_delivery_only"`
		}
	}
	return original
}

// Emit only the internal index wire from the same reflection/type generation.
// Keeping the file inside the knowledge package avoids widening its NodeNext
// rootDir or manually maintaining a second set of protocol interfaces.
func knowledgeIndexRuntimeTypes(types string) ([]byte, error) {
	parts := regexp.MustCompile(`(?ms)^export interface KnowledgeIndex[A-Za-z]+ \{\n.*?^\}\n`).FindAllString(types, -1)
	if len(parts) != 7 {
		return nil, fmt.Errorf("expected seven domain index wire interfaces, found %d", len(parts))
	}
	return []byte("// Generated by go run ./cmd/suma-contracts. Do not edit.\n" + strings.Join(parts, "\n")), nil
}

