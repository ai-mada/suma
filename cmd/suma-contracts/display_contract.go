// Only this explicitly approved producer group exports canonical templates.
// The ordinary public catalog still omits private SourceTemplate fields.
func displayLocalizationSource() ([]byte, error) {
	return displayLocalizationSourceFrom(displaycontract.SourceDefinitions())
}

func displayLocalizationSourceFrom(definitions []displaycontract.SourceDefinition) ([]byte, error) {
	expected := displaycontract.SourceDefinitions()
	if len(definitions) != len(expected) {
		return nil, fmt.Errorf("incomplete display source definitions")
	}
	approved := make(map[string][]byte, len(expected))
	for _, d := range expected {
		encoded, err := json.Marshal(d)
		if err != nil {
			return nil, err
		}
		approved[d.Key] = encoded
	}
	seen := map[string]bool{}
	ordered := make([]displaycontract.SourceDefinition, 0, len(definitions))
	for _, d := range definitions {
		encoded, err := json.Marshal(d)
		if err != nil || seen[d.Key] || !bytes.Equal(approved[d.Key], encoded) {
			return nil, fmt.Errorf("unapproved or changed display source definition: %s", d.Key)
		}
		seen[d.Key] = true
		ordered = append(ordered, d)
	}
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].Key < ordered[j].Key })
	var data bytes.Buffer
	encoder := json.NewEncoder(&data)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(ordered); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString("// Generated by go run ./cmd/suma-contracts. Do not edit.\n")
	out.WriteString("// Approved platform display sources only; raw reasons, authorization and execution facts remain separate.\n")
	out.WriteString("export type DisplaySourceDefinition={key:string;parameters:readonly {name:string;kind:'text'|'identifier'|'integer'}[];source_template:string};\n")
	out.WriteString("export const displaySourceDefinitions=")
	out.Write(bytes.TrimSpace(data.Bytes()))
	out.WriteString(" as const satisfies readonly DisplaySourceDefinition[];\n")
	return out.Bytes(), nil
}

func displayDiagnosticContracts(api map[string]any) {
	schemas := toolContractMap(api, "components", "schemas")
	diagnostic := toolContractMap(schemas, "DisplayDiagnostic")
	diagnostic["additionalProperties"] = false
	diagnostic["x-max-utf8-bytes"] = 4096
	diagnostic["description"] = "Optional source-bound current tool reason display identity. Full canonical equality with the same ToolProfile.reason is required. Never permission, model health, execution, test or acceptance evidence."
	toolContractMap(diagnostic, "properties", "schema_version")["const"] = 1
	keys := []string{}
	conditions := []any{}
	for _, source := range displaycontract.SourceDefinitions() {
		keys = append(keys, source.Key)
		properties := map[string]any{}
		required := []string{}
		for _, parameter := range source.Parameters {
			rule := map[string]any{"type": "string", "minLength": 1, "maxLength": 512, "x-max-utf8-bytes": 512, "description": "Well-formed UTF-8 without control characters. Literal data, not a nested display key."}
			if parameter.Kind == localization.Identifier {
				rule["pattern"] = `^[A-Za-z0-9_.:-]{1,100}$`
			} else if parameter.Kind == localization.Integer {
				rule = map[string]any{"type": "integer", "minimum": 0, "maximum": 9007199254740991, "x-integer-lexeme": true}
			}
			properties[parameter.Name] = rule
			required = append(required, parameter.Name)
		}
		params := map[string]any{"type": "object", "additionalProperties": false, "properties": properties}
		then := map[string]any{"properties": map[string]any{"message_params": params}}
		if len(required) > 0 {
			params["required"] = required
			then["required"] = []string{"message_params"}
		}
		conditions = append(conditions, map[string]any{"if": map[string]any{"required": []string{"message_key"}, "properties": map[string]any{"message_key": map[string]any{"const": source.Key}}}, "then": then})
	}
	toolContractMap(diagnostic, "properties", "message_key")["enum"] = keys
	diagnostic["allOf"] = conditions
	toolContractMap(schemas, "ToolProfile", "properties", "reason_diagnostic")["readOnly"] = true
}
