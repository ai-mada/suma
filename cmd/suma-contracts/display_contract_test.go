// These assertions exercise the published consumer contract, rather than the
// internal Go builder: raw reasons remain ordinary strings and only the new
// read-only field carries a closed, versioned display identity.
func TestDisplayDiagnosticPublishedContract(t *testing.T) {
	api, types := generate()
	schemas := api["components"].(map[string]any)["schemas"].(map[string]any)
	d, ok := schemas["DisplayDiagnostic"].(map[string]any)
	if !ok {
		t.Fatal("ToolProfile needs its source-bound display diagnostic schema")
	}
	if d["additionalProperties"] != false {
		t.Fatal("display diagnostic accepts arbitrary presentation fields")
	}
	properties := d["properties"].(map[string]any)
	if properties["schema_version"].(map[string]any)["const"] != 1 {
		t.Fatal("display diagnostic version is not fixed")
	}
	keys, ok := properties["message_key"].(map[string]any)["enum"].([]string)
	if !ok || len(keys) != 15 {
		t.Fatal("display contract must contain all approved tool reason identities")
	}
	for _, key := range keys {
		if !strings.HasPrefix(key, "display.tool.") {
			t.Fatal("unapproved display domain", key)
		}
	}
	profile := schemas["ToolProfile"].(map[string]any)["properties"].(map[string]any)
	if profile["reason"].(map[string]any)["type"] != "string" || profile["reason_diagnostic"].(map[string]any)["readOnly"] != true {
		t.Fatal("raw reason and read-only display identity are not distinct")
	}
	for _, name := range []string{"ToolProfileCreateRequest", "ToolProfileCommandRequest", "ToolObservation"} {
		props := schemas[name].(map[string]any)["properties"].(map[string]any)
		if _, exists := props["reason_diagnostic"]; exists {
			t.Fatal("write/observation schema accepts server display provenance", name)
		}
	}
	_, diagnosticType, exists := strings.Cut(types, "export interface DisplayDiagnostic {\n")
	if !exists || !strings.Contains(strings.SplitN(diagnosticType, "\n}\n", 2)[0], "schema_version: 1;") {
		t.Fatal("TypeScript loses the versioned display identity")
	}
}

func TestDisplaySourceGenerationRetainsExactApprovedDefinitions(t *testing.T) {
	definitions := displaycontract.SourceDefinitions()
	first, err := displayLocalizationSourceFrom(definitions)
	if err != nil {
		t.Fatal(err)
	}
	for left, right := 0, len(definitions)-1; left < right; left, right = left+1, right-1 {
		definitions[left], definitions[right] = definitions[right], definitions[left]
	}
	second, err := displayLocalizationSourceFrom(definitions)
	if err != nil || !bytes.Equal(first, second) {
		t.Fatal("declaration order changed the browser source contract", err)
	}
	for name, mutate := range map[string]func([]displaycontract.SourceDefinition) []displaycontract.SourceDefinition{
		"missing": func(defs []displaycontract.SourceDefinition) []displaycontract.SourceDefinition {
			return defs[:len(defs)-1]
		},
		"duplicate": func(defs []displaycontract.SourceDefinition) []displaycontract.SourceDefinition {
			defs[0] = defs[1]
			return defs
		},
		"future domain": func(defs []displaycontract.SourceDefinition) []displaycontract.SourceDefinition {
			defs[0].Key = "display.future.reason"
			return defs
		},
		"changed source": func(defs []displaycontract.SourceDefinition) []displaycontract.SourceDefinition {
			defs[0].SourceTemplate += " changed"
			return defs
		},
		"changed parameters": func(defs []displaycontract.SourceDefinition) []displaycontract.SourceDefinition {
			for i := range defs {
				if len(defs[i].Parameters) > 0 {
					defs[i].Parameters[0].Name = "foreign"
					break
				}
			}
			return defs
		},
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := displayLocalizationSourceFrom(mutate(displaycontract.SourceDefinitions())); err == nil {
				t.Fatal("unapproved source contract accepted")
			}
		})
	}
	file, err := os.ReadFile(filepath.Join("..", "..", "packages", "contracts", "src", "display-sources.ts"))
	if err != nil || !bytes.Equal(first, file) {
		t.Fatal("checked-in browser display source drift", err)
	}
}

func TestDisplaySourcesArtifactIsStandalone(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", "..", "packages", "contracts", "src", "display-sources.ts"))
	if err != nil {
		t.Fatalf("browser needs Go-generated canonical sources: %v", err)
	}
	text := string(data)
	if !strings.HasPrefix(text, "// Generated by go run ./cmd/suma-contracts. Do not edit.\n") || strings.Contains(text, "import ") {
		t.Fatal("display source module is not a standalone generated artifact")
	}
	parts := strings.SplitN(text, "export const displaySourceDefinitions=", 2)
	if len(parts) != 2 {
		t.Fatal("displaySourceDefinitions export missing")
	}
	var entries []map[string]json.RawMessage
	if err := json.Unmarshal([]byte(strings.SplitN(parts[1], " as const", 2)[0]), &entries); err != nil || len(entries) != 15 {
		t.Fatal("generated source definitions are incomplete or not serializable", err)
	}
}
