func TestNativeLocalizationGeneratedArtifactExists(t *testing.T) {
	path := filepath.Join("..", "..", "packages", "agent-runtime", "src", "native-catalog.ts")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("native SDK needs a generated catalog from the Go definitions: %v", err)
	}
	if !strings.HasPrefix(string(data), "// Generated by go run ./cmd/suma-contracts. Do not edit.\n") {
		t.Fatal("native catalog does not identify its generator")
	}
}

func TestNativeLocalizationGenerationIsDeterministicAndComplete(t *testing.T) {
	first, err := nativeLocalizationSource()
	if err != nil {
		t.Fatal(err)
	}
	definitions := localization.NativeCatalog()
	for left, right := 0, len(definitions)-1; left < right; left, right = left+1, right-1 {
		definitions[left], definitions[right] = definitions[right], definitions[left]
	}
	second, err := nativeLocalizationSourceFrom(definitions)
	if err != nil || !bytes.Equal(first, second) {
		t.Fatal("source order changed generated native module", err)
	}
	type entry struct {
		En     string            `json:"en"`
		Zh     string            `json:"zh"`
		Params map[string]string `json:"params"`
	}
	parts := strings.SplitN(string(first), "export const nativeCatalog=", 2)
	if len(parts) != 2 {
		t.Fatal("standalone native catalog missing")
	}
	object := strings.SplitN(parts[1], " as const satisfies", 2)[0]
	object = strings.TrimSuffix(strings.TrimSuffix(object, "\n}"), ",") + "\n}"
	var generated map[string]entry
	if err := json.Unmarshal([]byte(object), &generated); err != nil {
		t.Fatal("generated catalog is not a plain serializable object", err)
	}
	if len(generated) != 50 {
		t.Fatalf("generated native key count: %d", len(generated))
	}
	for _, definition := range localization.NativeCatalog() {
		got, exists := generated[definition.Key]
		if !exists || got.En != definition.Texts[localization.EnUS] || got.Zh != definition.Texts[localization.ZhCN] || len(got.Params) != len(definition.Parameters) {
			t.Fatal("Go/SDK text or parameter parity lost", definition.Key)
		}
		for _, parameter := range definition.Parameters {
			if got.Params[parameter.Name] != string(parameter.Kind) {
				t.Fatal("SDK parameter kind differs", definition.Key)
			}
		}
	}
	path := filepath.Join("..", "..", "packages", "agent-runtime", "src", "native-catalog.ts")
	checkedIn, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, checkedIn) {
		t.Fatal("generated native catalog drift; run go run ./cmd/suma-contracts")
	}
}

func TestNativeLocalizationGenerationRejectsUntrustedOrIncompleteDefinitions(t *testing.T) {
	for _, mutation := range []func([]localization.Definition) []localization.Definition{
		func(ds []localization.Definition) []localization.Definition { return ds[:len(ds)-1] },
		func(ds []localization.Definition) []localization.Definition {
			ds[0].Key = "native.future.new"
			return ds
		},
		func(ds []localization.Definition) []localization.Definition { ds[0].SourceTemplate = ""; return ds },
		func(ds []localization.Definition) []localization.Definition {
			ds[0].SourceTemplate = "partial"
			return ds
		},
		func(ds []localization.Definition) []localization.Definition {
			ds[0].Texts[localization.ZhCN] = ""
			return ds
		},
		func(ds []localization.Definition) []localization.Definition { ds[0] = ds[1]; return ds },
		func(ds []localization.Definition) []localization.Definition {
			ds[0].Parameters = []localization.Parameter{{Name: "unsafe", Kind: localization.Identifier}}
			return ds
		},
		func(ds []localization.Definition) []localization.Definition {
			ds[0].Parameters = []localization.Parameter{{Name: "status", Kind: localization.Text}, {Name: "status", Kind: localization.Text}}
			return ds
		},
	} {
		if _, err := nativeLocalizationSourceFrom(mutation(localization.NativeCatalog())); err == nil {
			t.Fatal("invalid native definitions were generated")
		}
	}
}
